#!/usr/bin/env node
// @ts-check
// Generates reef-vcs's code from the schema (R2.07, ADR 0054). `npm run gen` runs it, and so does
// every script that builds, checks or tests. Writes, under src/gen/ (all VCS-ignored):
//
// - reef/api/v1/*_pb.ts: protoc-gen-es's messages and services for every v1 file;
// - rpcs.ts, methods.ts and api-v1.ts: the client's methods (protoc-gen-reef.mjs);
// - reef/daemon/v0/*_pb.ts: 0.1's frozen status messages, for the incompatible-daemon probe;
// - build.ts: the version, the API revision and the commit;
//
// and copies the repository's LICENSE beside package.json. Needs no network: buf and both plugins
// are local.

import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { delimiter, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const SDK = dirname(HERE);
export const ROOT = dirname(dirname(SDK));
const PROTO = join(ROOT, "crates", "reef-api", "proto");
const OUT = join(SDK, "src", "gen");
const V0 = ["reef/daemon/v0/daemon.proto", "reef/daemon/v0/error.proto"];

/** `[workspace.package] version` from the repository's Cargo.toml. */
export function workspaceVersion() {
  const text = readFileSync(join(ROOT, "Cargo.toml"), "utf8");
  const section = text.split(/^\[workspace\.package\]\s*$/m)[1];
  const match = section?.split(/^\[/m)[0]?.match(/^version\s*=\s*"([^"]+)"\s*$/m);
  if (!match?.[1]) {
    throw new Error("Cargo.toml has no [workspace.package] version");
  }
  return match[1];
}

/** `reef_api::API_REVISION`, read from reef-api's lib.rs. */
export function apiRevision() {
  const text = readFileSync(join(ROOT, "crates", "reef-api", "src", "lib.rs"), "utf8");
  const match = text.match(/^pub const API_REVISION: u32 = (\d+);$/m);
  if (!match?.[1]) {
    throw new Error("crates/reef-api/src/lib.rs has no `pub const API_REVISION: u32 = N;` line");
  }
  return Number(match[1]);
}

/** The checkout's short commit, from git or jj; empty when neither knows. */
export function commit() {
  /** @type {[string, string[]][]} */
  const tries = [
    ["git", ["rev-parse", "--short=12", "HEAD"]],
    ["jj", ["log", "-r", "@", "--no-graph", "-T", "commit_id.short(12)"]],
  ];
  for (const [command, args] of tries) {
    try {
      const out = execFileSync(command, args, {
        cwd: ROOT,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      }).trim();
      if (/^[0-9a-f]{7,}$/.test(out)) {
        return out;
      }
    } catch {
      // Not a checkout this tool knows.
    }
  }
  return "";
}

function buf() {
  return join(SDK, "node_modules", ".bin", "buf");
}

/**
 * @param {string[]} args
 */
function run(args) {
  // protoc-gen-es from this package's node_modules, as `npm run` would find it.
  const path = [join(SDK, "node_modules", ".bin"), process.env["PATH"] ?? ""].join(delimiter);
  execFileSync(buf(), args, {
    cwd: SDK,
    env: { ...process.env, PATH: path },
    stdio: ["ignore", "inherit", "inherit"],
  });
}

function main() {
  run(["generate", "--template", "buf.gen.yaml"]);
  // The root module excludes v0 even when its proto directory is the input, so v0 is generated
  // from a copy outside the repository.
  const scratch = mkdtempSync(join(tmpdir(), "reef-v0-"));
  try {
    for (const file of V0) {
      mkdirSync(dirname(join(scratch, file)), { recursive: true });
      copyFileSync(join(PROTO, file), join(scratch, file));
    }
    writeFileSync(join(scratch, "buf.yaml"), "version: v2\n");
    run(["generate", scratch, "--template", "buf.gen.v0.yaml"]);
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
  const build = [
    "// Generated by codegen/generate.mjs; do not edit.",
    "",
    "/** This SDK's version: the reef workspace's, which the daemon it talks to should match. */",
    `export const VERSION = ${JSON.stringify(workspaceVersion())};`,
    "/** The API revision this SDK was generated at (`reef_api::API_REVISION`). */",
    `export const API_REVISION = ${apiRevision()};`,
    "/** The commit this SDK was built from; empty when unknown. */",
    `export const COMMIT = ${JSON.stringify(commit())};`,
    "",
  ].join("\n");
  writeFileSync(join(OUT, "build.ts"), build);
  copyFileSync(join(ROOT, "LICENSE"), join(SDK, "LICENSE"));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
