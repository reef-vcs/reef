//! The remote listener's TLS (R2.08, ADR 0049), terminated by Reef with
//! rustls on ring rather than by tonic: ALPN offers `h2` and `http/1.1`
//! (gRPC-web's fallback), the certificate reloads without a restart, and
//! the crypto provider is chosen here, not installed process-wide.
//!
//! The certificate is one of two:
//!
//! - **Generated** (the default): an ECDSA P-256 key made once, kept in
//!   `<state>/remote/key.pem` (`0600`), and a self-signed certificate for
//!   it in `cert.pem`, for `[remote] names` (default: the host name),
//!   valid for 397 days. With 30 days left, or other names, the daemon
//!   issues a new certificate for the same key, at start and on a daily
//!   check. Clients pin the key, so renewal never breaks a pin.
//! - **Supplied** (`[remote] tls_cert` and `tls_key`): re-read during a
//!   handshake when either file's mtime or size changed, checked at most
//!   once a minute. A pair that does not load keeps the previous one
//!   serving, and the status says why.

use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex, PoisonError};
use std::time::{Duration, Instant, SystemTime};

use rcgen::{CertificateParams, KeyPair, PKCS_ECDSA_P256_SHA256};
use rustls::ServerConfig;
use rustls::crypto::CryptoProvider;
use rustls::pki_types::pem::PemObject as _;
use rustls::pki_types::{CertificateDer, PrivateKeyDer, PrivatePkcs8KeyDer};
use rustls::server::{ClientHello, ResolvesServerCert};
use rustls::sign::CertifiedKey;

use super::Limits;
use crate::model::Timestamp;

/// Where the certificate comes from.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Source {
    /// Generated by the daemon; clients pin its key.
    Generated,
    /// `[remote] tls_cert` and `tls_key`.
    File,
}

/// What the status reports about the certificate.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CertInfo {
    /// Where it comes from.
    pub source: Source,
    /// `sha256:<hex>` of the leaf's `SubjectPublicKeyInfo`.
    pub fingerprint: String,
    /// When the leaf expires.
    pub not_after: Timestamp,
    /// The leaf's subject alternative names, DNS names and IP addresses.
    pub subject_names: Vec<String>,
}

/// A certificate that cannot be loaded, generated or written.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum TlsError {
    /// A file could not be read or written.
    #[error("{}", path.display())]
    Io {
        /// The file.
        path: PathBuf,
        /// The error.
        #[source]
        source: std::io::Error,
    },
    /// A PEM file holds no certificate or key, or one that does not parse.
    #[error("{} is not a PEM {what}", path.display())]
    Pem {
        /// The file.
        path: PathBuf,
        /// `certificate chain` or `private key`.
        what: &'static str,
    },
    /// The key does not match the leaf, or rustls refused them.
    #[error("the certificate and key do not make a usable pair")]
    Pair(#[source] rustls::Error),
    /// The certificate could not be generated.
    #[error("cannot generate the remote listener's certificate")]
    Generate(#[source] rcgen::Error),
    /// The leaf does not parse as X.509.
    #[error("the certificate does not parse")]
    Parse,
}

/// The crypto provider every remote TLS config uses: ring.
pub(crate) fn provider() -> Arc<CryptoProvider> {
    Arc::new(rustls::crypto::ring::default_provider())
}

/// The server config over `resolver`: TLS 1.3 and 1.2, ALPN `h2` then
/// `http/1.1`, no client certificates, no 0-RTT.
pub(crate) fn server_config(resolver: Arc<Resolver>) -> Result<ServerConfig, rustls::Error> {
    let mut config = ServerConfig::builder_with_provider(provider())
        .with_protocol_versions(&[&rustls::version::TLS13, &rustls::version::TLS12])?
        .with_no_client_auth()
        .with_cert_resolver(resolver);
    config.alpn_protocols = vec![b"h2".to_vec(), b"http/1.1".to_vec()];
    config.max_early_data_size = 0;
    Ok(config)
}

/// What a supplied pair's files looked like when last read.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct Stamp {
    cert: Option<(SystemTime, u64)>,
    key: Option<(SystemTime, u64)>,
}

fn stamp_of(path: &Path) -> Option<(SystemTime, u64)> {
    let metadata = std::fs::metadata(path).ok()?;
    Some((metadata.modified().ok()?, metadata.len()))
}

#[derive(Debug)]
struct Supplied {
    cert: PathBuf,
    key: PathBuf,
    checked: Instant,
    stamp: Stamp,
}

#[derive(Debug)]
struct Current {
    key: Arc<CertifiedKey>,
    info: CertInfo,
    /// Why the last reload or renewal failed.
    error: Option<String>,
}

/// The certificate the listener presents: swapped on renewal or reload.
#[derive(Debug)]
pub struct Resolver {
    current: Mutex<Current>,
    supplied: Option<Mutex<Supplied>>,
    reload_interval: Duration,
}

impl ResolvesServerCert for Resolver {
    fn resolve(&self, _hello: ClientHello<'_>) -> Option<Arc<CertifiedKey>> {
        self.reload_if_due();
        Some(Arc::clone(&self.lock().key))
    }
}

impl Resolver {
    fn lock(&self) -> std::sync::MutexGuard<'_, Current> {
        self.current.lock().unwrap_or_else(PoisonError::into_inner)
    }

    /// The certificate as the status reports it, and the last reload or
    /// renewal error.
    pub fn info(&self) -> (CertInfo, Option<String>) {
        let current = self.lock();
        (current.info.clone(), current.error.clone())
    }

    /// The supplied pair at `cert` and `key`.
    pub fn supplied(cert: &Path, key: &Path, limits: &Limits) -> Result<Resolver, TlsError> {
        let stamp = Stamp {
            cert: stamp_of(cert),
            key: stamp_of(key),
        };
        let (key_pair, info) = load_pair(cert, key)?;
        Ok(Resolver {
            current: Mutex::new(Current {
                key: Arc::new(key_pair),
                info,
                error: None,
            }),
            supplied: Some(Mutex::new(Supplied {
                cert: cert.to_owned(),
                key: key.to_owned(),
                checked: Instant::now(),
                stamp,
            })),
            reload_interval: limits.cert_reload_interval,
        })
    }

    /// The generated certificate in `dir` for `names`, made or renewed as
    /// needed.
    pub fn generated(dir: &Path, names: &[String], limits: &Limits) -> Result<Resolver, TlsError> {
        let (key, info) = Generated::load(dir, names, limits)?;
        Ok(Resolver {
            current: Mutex::new(Current {
                key: Arc::new(key),
                info,
                error: None,
            }),
            supplied: None,
            reload_interval: limits.cert_reload_interval,
        })
    }

    /// The daily check of a generated certificate: renews it, with the same
    /// key, when it is due.
    pub fn renew_if_due(&self, dir: &Path, names: &[String], limits: &Limits) {
        if self.supplied.is_some() {
            return;
        }
        match Generated::load(dir, names, limits) {
            Ok((key, info)) => {
                let mut current = self.lock();
                if current.info != info {
                    tracing::info!(not_after = %info.not_after, "remote listener certificate renewed");
                }
                *current = Current {
                    key: Arc::new(key),
                    info,
                    error: None,
                };
            }
            Err(error) => {
                let chain = reef_lib::error::ErrorChain(&error).to_string();
                tracing::warn!(error = %chain, "cannot renew the remote listener's certificate");
                self.lock().error = Some(chain);
            }
        }
    }

    /// Re-reads a supplied pair whose files changed, at most once per
    /// reload interval.
    fn reload_if_due(&self) {
        let Some(supplied) = &self.supplied else {
            return;
        };
        let mut supplied = supplied.lock().unwrap_or_else(PoisonError::into_inner);
        if supplied.checked.elapsed() < self.reload_interval {
            return;
        }
        supplied.checked = Instant::now();
        let stamp = Stamp {
            cert: stamp_of(&supplied.cert),
            key: stamp_of(&supplied.key),
        };
        if stamp == supplied.stamp {
            return;
        }
        // The stamp moves only on success, so a broken pair is retried each
        // interval until it loads.
        match load_pair(&supplied.cert, &supplied.key) {
            Ok((key, info)) => {
                supplied.stamp = stamp;
                tracing::info!(
                    fingerprint = %info.fingerprint,
                    not_after = %info.not_after,
                    "remote listener certificate reloaded"
                );
                *self.lock() = Current {
                    key: Arc::new(key),
                    info,
                    error: None,
                };
            }
            Err(error) => {
                let chain = reef_lib::error::ErrorChain(&error).to_string();
                tracing::warn!(error = %chain, "cannot reload the remote listener's certificate; the previous one keeps serving");
                self.lock().error = Some(chain);
            }
        }
    }
}

/// Reads a supplied chain and key.
fn load_pair(cert: &Path, key: &Path) -> Result<(CertifiedKey, CertInfo), TlsError> {
    let io = |path: &Path| {
        let path = path.to_owned();
        move |source| TlsError::Io { path, source }
    };
    let cert_pem = std::fs::read(cert).map_err(io(cert))?;
    let key_pem = std::fs::read(key).map_err(io(key))?;
    let chain: Vec<CertificateDer<'static>> = CertificateDer::pem_slice_iter(&cert_pem)
        .collect::<Result<_, _>>()
        .ok()
        .filter(|chain: &Vec<_>| !chain.is_empty())
        .ok_or_else(|| TlsError::Pem {
            path: cert.to_owned(),
            what: "certificate chain",
        })?;
    let private = PrivateKeyDer::from_pem_slice(&key_pem).map_err(|_| TlsError::Pem {
        path: key.to_owned(),
        what: "private key",
    })?;
    let info = info_of(&chain[0], Source::File)?;
    let certified = CertifiedKey::from_der(chain, private, &provider()).map_err(TlsError::Pair)?;
    Ok((certified, info))
}

/// What the status reports about `leaf`.
fn info_of(leaf: &CertificateDer<'_>, source: Source) -> Result<CertInfo, TlsError> {
    let fingerprint = reef_client::remote::fingerprint(leaf).ok_or(TlsError::Parse)?;
    let parsed = der::leaf(leaf).ok_or(TlsError::Parse)?;
    Ok(CertInfo {
        source,
        fingerprint,
        not_after: parsed.not_after,
        subject_names: parsed.names,
    })
}

/// The generated key and certificate.
struct Generated;

impl Generated {
    const KEY: &'static str = "key.pem";
    const CERT: &'static str = "cert.pem";

    /// Loads `dir`'s key (making one if there is none) and certificate,
    /// issuing a new certificate for the same key when there is none, it
    /// expires within `cert_renew_before`, or its names are not `names`.
    fn load(
        dir: &Path,
        names: &[String],
        limits: &Limits,
    ) -> Result<(CertifiedKey, CertInfo), TlsError> {
        let io = |path: &Path| {
            let path = path.to_owned();
            move |source| TlsError::Io { path, source }
        };
        crate::daemon::ensure_private_dir(dir, true).map_err(|error| TlsError::Io {
            path: dir.to_owned(),
            source: std::io::Error::other(error),
        })?;
        let key_path = dir.join(Self::KEY);
        let cert_path = dir.join(Self::CERT);
        let key_pair = match std::fs::read_to_string(&key_path) {
            Ok(pem) => {
                use std::os::unix::fs::PermissionsExt as _;
                // Tightened if something loosened it (S-45).
                if let Ok(metadata) = std::fs::metadata(&key_path)
                    && metadata.permissions().mode() & 0o077 != 0
                {
                    std::fs::set_permissions(&key_path, std::fs::Permissions::from_mode(0o600))
                        .map_err(io(&key_path))?;
                }
                KeyPair::from_pem(&pem).map_err(|_| TlsError::Pem {
                    path: key_path.clone(),
                    what: "private key",
                })?
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                let key_pair =
                    KeyPair::generate_for(&PKCS_ECDSA_P256_SHA256).map_err(TlsError::Generate)?;
                write_private(&key_path, key_pair.serialize_pem().as_bytes())
                    .map_err(io(&key_path))?;
                tracing::info!(path = %key_path.display(), "generated the remote listener's key");
                key_pair
            }
            Err(error) => return Err(io(&key_path)(error)),
        };
        let now = Timestamp::now();
        let renew_at = |info: &CertInfo| {
            Timestamp(
                info.not_after
                    .0
                    .saturating_sub(crate::model::duration_millis(limits.cert_renew_before)),
            )
        };
        let existing = std::fs::read(&cert_path)
            .ok()
            .and_then(|pem| CertificateDer::from_pem_slice(&pem).ok())
            .and_then(|der| Some((info_of(&der, Source::Generated).ok()?, der)));
        let wanted = sorted(names);
        let (leaf, info) = match existing {
            Some((info, der))
                if renew_at(&info) > now
                    && sorted(&info.subject_names) == wanted
                    && same_key(&der, &key_pair) =>
            {
                (der, info)
            }
            _ => {
                let mut params =
                    CertificateParams::new(names.to_vec()).map_err(TlsError::Generate)?;
                let start = time::OffsetDateTime::now_utc() - time::Duration::hours(1);
                params.not_before = start;
                params.not_after = start
                    + time::Duration::try_from(limits.cert_validity)
                        .unwrap_or(time::Duration::days(397));
                params
                    .distinguished_name
                    .push(rcgen::DnType::CommonName, "reef daemon");
                let cert = params.self_signed(&key_pair).map_err(TlsError::Generate)?;
                write_private(&cert_path, cert.pem().as_bytes()).map_err(io(&cert_path))?;
                let der = cert.der().clone();
                let info = info_of(&der, Source::Generated)?;
                tracing::info!(
                    fingerprint = %info.fingerprint,
                    not_after = %info.not_after,
                    "issued the remote listener's certificate"
                );
                (der, info)
            }
        };
        let private = PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(key_pair.serialize_der()));
        let certified =
            CertifiedKey::from_der(vec![leaf], private, &provider()).map_err(TlsError::Pair)?;
        Ok((certified, info))
    }
}

fn sorted(names: &[String]) -> Vec<String> {
    let mut names = names.to_vec();
    names.sort();
    names.dedup();
    names
}

/// Whether `leaf` certifies `key`'s public key.
fn same_key(leaf: &CertificateDer<'_>, key: &KeyPair) -> bool {
    use rcgen::PublicKeyData as _;
    webpki::EndEntityCert::try_from(leaf).is_ok_and(|cert| {
        cert.subject_public_key_info().as_ref() == key.subject_public_key_info().as_slice()
    })
}

/// Writes `bytes` to `path` with mode `0600`, through a temporary file in
/// the same directory, so a reader never sees half a file.
fn write_private(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    use std::io::Write as _;
    use std::os::unix::fs::OpenOptionsExt as _;
    let tmp = path.with_extension("tmp");
    let _ = std::fs::remove_file(&tmp);
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(&tmp)?;
    file.write_all(bytes)?;
    file.sync_all()?;
    std::fs::rename(&tmp, path)
}

/// Just enough DER to read a leaf's validity end and subject alternative
/// names, which neither rustls nor webpki expose.
mod der {
    use crate::model::Timestamp;

    /// A certificate's `notAfter` and its DNS and IP subject alternative
    /// names.
    pub(super) struct Leaf {
        pub(super) not_after: Timestamp,
        pub(super) names: Vec<String>,
    }

    /// One TLV: its tag, its content, and what follows it.
    fn tlv(input: &[u8]) -> Option<(u8, &[u8], &[u8])> {
        let (&tag, rest) = input.split_first()?;
        let (&first, rest) = rest.split_first()?;
        let (len, rest) = if first < 0x80 {
            (usize::from(first), rest)
        } else {
            let count = usize::from(first & 0x7f);
            if count == 0 || count > 4 || rest.len() < count {
                return None;
            }
            let (bytes, rest) = rest.split_at(count);
            let len = bytes
                .iter()
                .fold(0_usize, |len, &b| (len << 8) | usize::from(b));
            (len, rest)
        };
        (rest.len() >= len).then(|| (tag, &rest[..len], &rest[len..]))
    }

    /// The content of the TLV at the start of `input` if its tag is `tag`.
    fn expect(input: &[u8], tag: u8) -> Option<(&[u8], &[u8])> {
        let (found, content, rest) = tlv(input)?;
        (found == tag).then_some((content, rest))
    }

    const SEQUENCE: u8 = 0x30;
    /// id-ce-subjectAltName, 2.5.29.17.
    const SAN_OID: &[u8] = &[0x55, 0x1d, 0x11];

    pub(super) fn leaf(der: &[u8]) -> Option<Leaf> {
        let (cert, _) = expect(der, SEQUENCE)?;
        let (tbs, _) = expect(cert, SEQUENCE)?;
        let mut rest = tbs;
        // [0] EXPLICIT version, optional.
        if let Some((0xa0, _, after)) = tlv(rest) {
            rest = after;
        }
        // serialNumber, signature, issuer.
        for _ in 0..3 {
            rest = tlv(rest)?.2;
        }
        let (validity, after) = expect(rest, SEQUENCE)?;
        let (_, _, validity_rest) = tlv(validity)?;
        let (time_tag, not_after, _) = tlv(validity_rest)?;
        let not_after = time(time_tag, not_after)?;
        // subject, subjectPublicKeyInfo.
        rest = tlv(tlv(after)?.2)?.2;
        let mut names = Vec::new();
        while let Some((tag, content, after)) = tlv(rest) {
            rest = after;
            if tag != 0xa3 {
                continue;
            }
            let (extensions, _) = expect(content, SEQUENCE)?;
            let mut extensions = extensions;
            while let Some((extension, after)) = expect(extensions, SEQUENCE) {
                extensions = after;
                let (oid, mut fields) = expect(extension, 0x06)?;
                if oid != SAN_OID {
                    continue;
                }
                if let Some((0x01, _, after)) = tlv(fields) {
                    fields = after;
                }
                let (value, _) = expect(fields, 0x04)?;
                let (general_names, _) = expect(value, SEQUENCE)?;
                let mut general_names = general_names;
                while let Some((tag, name, after)) = tlv(general_names) {
                    general_names = after;
                    match tag {
                        0x82 => names.push(String::from_utf8_lossy(name).into_owned()),
                        0x87 => names.extend(ip(name)),
                        _ => {}
                    }
                }
            }
        }
        Some(Leaf { not_after, names })
    }

    fn ip(bytes: &[u8]) -> Option<String> {
        match bytes.len() {
            4 => Some(std::net::Ipv4Addr::from(<[u8; 4]>::try_from(bytes).ok()?).to_string()),
            16 => Some(std::net::Ipv6Addr::from(<[u8; 16]>::try_from(bytes).ok()?).to_string()),
            _ => None,
        }
    }

    /// `UTCTime` (`YYMMDDHHMMSSZ`) or `GeneralizedTime` (`YYYYMMDDHHMMSSZ`).
    fn time(tag: u8, text: &[u8]) -> Option<Timestamp> {
        let text = std::str::from_utf8(text).ok()?.strip_suffix('Z')?;
        let (year, rest) = match tag {
            0x17 => {
                let year: i32 = text.get(..2)?.parse().ok()?;
                (
                    if year >= 50 { 1900 + year } else { 2000 + year },
                    &text[2..],
                )
            }
            0x18 => (text.get(..4)?.parse().ok()?, &text[4..]),
            _ => return None,
        };
        let field = |at: usize| rest.get(at..at + 2)?.parse::<u8>().ok();
        let month = time::Month::try_from(field(0)?).ok()?;
        let date = time::Date::from_calendar_date(year, month, field(2)?).ok()?;
        let clock = time::Time::from_hms(field(4)?, field(6)?, field(8)?).ok()?;
        Some(Timestamp::from(
            time::PrimitiveDateTime::new(date, clock).assume_utc(),
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_keeps_its_key_across_renewals() {
        let dir = tempfile::tempdir().unwrap();
        let state = dir.path().join("remote");
        let names = vec!["vm.example".to_owned(), "10.0.0.5".to_owned()];
        let limits = Limits::default();
        let (_, first) = Generated::load(&state, &names, &limits).unwrap();
        assert_eq!(first.source, Source::Generated);
        assert!(first.fingerprint.starts_with("sha256:"));
        assert_eq!(sorted(&first.subject_names), sorted(&names));
        let year = 365 * 24 * 3_600_000;
        assert!(first.not_after.0 - Timestamp::now().0 > year);
        {
            use std::os::unix::fs::PermissionsExt as _;
            let mode = |path: &Path| std::fs::metadata(path).unwrap().permissions().mode() & 0o777;
            assert_eq!(mode(&state), 0o700);
            assert_eq!(mode(&state.join("key.pem")), 0o600);
            assert_eq!(mode(&state.join("cert.pem")), 0o600);
        }
        // Loaded again: the same certificate.
        let (_, again) = Generated::load(&state, &names, &limits).unwrap();
        assert_eq!(again, first);
        // Other names: a new certificate for the same key.
        let other = vec!["vm2.example".to_owned()];
        let (_, renamed) = Generated::load(&state, &other, &limits).unwrap();
        assert_eq!(renamed.fingerprint, first.fingerprint);
        assert_eq!(renamed.subject_names, other);
        // Due for renewal: a new expiry, the same key.
        std::fs::remove_file(state.join("cert.pem")).unwrap();
        let short = Limits {
            cert_validity: Duration::from_hours(20 * 24),
            ..limits
        };
        let (_, short_lived) = Generated::load(&state, &other, &short).unwrap();
        assert_eq!(short_lived.fingerprint, first.fingerprint);
        let (_, renewed) = Generated::load(&state, &other, &limits).unwrap();
        assert_eq!(renewed.fingerprint, first.fingerprint);
        assert!(renewed.not_after > short_lived.not_after);
    }

    #[test]
    fn supplied_pairs_are_checked() {
        let dir = tempfile::tempdir().unwrap();
        let key = KeyPair::generate_for(&PKCS_ECDSA_P256_SHA256).unwrap();
        let other = KeyPair::generate_for(&PKCS_ECDSA_P256_SHA256).unwrap();
        let cert = CertificateParams::new(vec!["vm.example".to_owned()])
            .unwrap()
            .self_signed(&key)
            .unwrap();
        let (cert_path, key_path) = (dir.path().join("c.pem"), dir.path().join("k.pem"));
        std::fs::write(&cert_path, cert.pem()).unwrap();
        std::fs::write(&key_path, key.serialize_pem()).unwrap();
        let (_, info) = load_pair(&cert_path, &key_path).unwrap();
        assert_eq!(info.source, Source::File);
        assert_eq!(info.subject_names, ["vm.example"]);
        std::fs::write(&key_path, other.serialize_pem()).unwrap();
        assert!(matches!(
            load_pair(&cert_path, &key_path),
            Err(TlsError::Pair(_))
        ));
        std::fs::write(&key_path, "nope").unwrap();
        assert!(matches!(
            load_pair(&cert_path, &key_path),
            Err(TlsError::Pem { .. })
        ));
    }
}
