/// blake3 of the v1 descriptors without comments, as of [`API_REVISION`]:
/// the last of [`API_DIGESTS`].
pub const API_DIGEST: &str = API_DIGESTS[API_DIGESTS.len() - 1];

/// The v1 files and their imports, with comments, as an encoded
/// `google.protobuf.FileDescriptorSet`, for SDK generators and reflection.
pub const FILE_DESCRIPTOR_SET: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/reef_api_v1.fds"));

/// The digest of the schema as built, for the test against [`API_DIGEST`].
#[cfg(test)]
const BUILT_DIGEST: &str = include!(concat!(env!("OUT_DIR"), "/digest.rs"));

/// `(path, access)` for every v1 method, sorted by path.
const ACCESS: &[(&str, i32)] = include!(concat!(env!("OUT_DIR"), "/access.rs"));

/// The access level of the v1 method at `path` (`/reef.api.v1.<Service>/<Rpc>`),
/// or `None` for a path that is not one.
pub fn access(path: &str) -> Option<v1::Access> {
    let index = ACCESS.binary_search_by(|(p, _)| (*p).cmp(path)).ok()?;
    v1::Access::try_from(ACCESS[index].1).ok()
}

/// Every v1 method's path, sorted.
pub fn methods() -> impl Iterator<Item = &'static str> {
    ACCESS.iter().map(|(path, _)| *path)
}

