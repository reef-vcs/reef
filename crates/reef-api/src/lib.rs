#[cfg(test)]
mod tests {
    use prost_reflect::{DescriptorPool, Kind, MessageDescriptor};

    use super::*;

    fn pool() -> DescriptorPool {
        DescriptorPool::decode(FILE_DESCRIPTOR_SET).unwrap()
    }

    fn methods_of(pool: &DescriptorPool) -> Vec<prost_reflect::MethodDescriptor> {
        pool.services()
            .filter(|service| service.package_name() == "reef.api.v1")
            .flat_map(|service| service.methods().collect::<Vec<_>>())
            .collect()
    }

    fn path(method: &prost_reflect::MethodDescriptor) -> String {
        format!("/{}/{}", method.parent_service().full_name(), method.name())
    }

    #[test]
    fn api_digest_matches_revision() {
        let revisions = API_DIGESTS.len();
        assert_eq!(
            API_DIGEST,
            BUILT_DIGEST,
            "the v1 schema changed: append {BUILT_DIGEST:?} to API_DIGESTS and bump API_REVISION \
             to {} (ADR 0029's checklist, items 1 and 2)",
            revisions + 1
        );
        assert_eq!(
            usize::try_from(API_REVISION).unwrap(),
            revisions,
            "API_DIGESTS has {revisions} entries: API_REVISION must be {revisions}"
        );
    }

    #[test]
    fn every_method_has_access() {
        let pool = pool();
        let methods = methods_of(&pool);
        assert!(methods.len() >= 30, "{}", methods.len());
        for method in &methods {
            let access = access(&path(method));
            assert!(
                access.is_some_and(|access| access != v1::Access::Unspecified),
                "{}",
                path(method)
            );
        }
        assert_eq!(super::methods().count(), methods.len());
        assert_eq!(access("/reef.api.v1.WorkspaceService/Nope"), None);
        assert_eq!(
            access("/reef.api.v1.RepositoryService/RegisterRepository"),
            Some(v1::Access::Admin)
        );
    }

    #[test]
    fn no_client_streaming() {
        for method in methods_of(&pool()) {
            assert!(!method.is_client_streaming(), "{}", path(&method));
        }
    }

    fn field_kind(message: &MessageDescriptor, name: &str) -> Option<Kind> {
        message.get_field_by_name(name).map(|field| field.kind())
    }

    #[test]
    fn lists_are_paginated() {
        for method in methods_of(&pool()) {
            if !(method.name().starts_with("List") || method.name() == "GetDiff") {
                continue;
            }
            let (input, output) = (method.input(), method.output());
            assert_eq!(
                field_kind(&input, "page_size"),
                Some(Kind::Int32),
                "{}",
                path(&method)
            );
            assert_eq!(
                field_kind(&input, "page_token"),
                Some(Kind::String),
                "{}",
                path(&method)
            );
            assert_eq!(
                field_kind(&output, "next_page_token"),
                Some(Kind::String),
                "{}",
                path(&method)
            );
        }
    }

    #[test]
    fn writes_return_operations() {
        // ADR 0029 decision 12's exceptions, and the symbol index's upload,
        // which stores derived data and records no operation (ADR 0042).
        const EXCEPT: [&str; 4] = [
            "RenewLease",
            "ReportPresence",
            "ClearPresence",
            "UploadScipDocuments",
        ];
        for method in methods_of(&pool()) {
            if access(&path(&method)) != Some(v1::Access::Write) || EXCEPT.contains(&method.name())
            {
                continue;
            }
            let field = method.output().get_field_by_name("operation");
            let message = field.and_then(|field| match field.kind() {
                Kind::Message(message) => Some(message.full_name().to_owned()),
                _ => None,
            });
            assert_eq!(
                message.as_deref(),
                Some("reef.api.v1.Operation"),
                "{}",
                path(&method)
            );
        }
    }

    #[test]
    fn enum_zero_is_unspecified() {
        let pool = pool();
        let enums: Vec<_> = pool
            .all_enums()
            .filter(|e| e.package_name() == "reef.api.v1")
            .collect();
        assert!(enums.len() >= 20, "{}", enums.len());
        for descriptor in enums {
            let zero = descriptor.get_value(0).unwrap();
            assert!(
                zero.name().ends_with("_UNSPECIFIED"),
                "{}: {}",
                descriptor.full_name(),
                zero.name()
            );
        }
    }

    #[test]
    fn error_detail_round_trips() {
        let detail = v1::ErrorDetail {
            kind: v1::ErrorKind::Unsupported.into(),
            reason: error::NOT_IMPLEMENTED.to_owned(),
            chain: vec!["outer".into(), "inner".into()],
            hint: "Upgrade.".into(),
            next: vec!["reef".into(), "daemon".into(), "stop".into()],
            metadata: [("method".to_owned(), "/x/Y".to_owned())].into(),
        };
        let status = error::status(tonic::Code::Unimplemented, "outer: inner".into(), &detail);
        assert_eq!(status.code(), tonic::Code::Unimplemented);
        assert_eq!(status.message(), "outer: inner");
        assert_eq!(error::detail(&status), Some(detail));
        assert_eq!(error::detail(&tonic::Status::not_found("x")), None);
        let raw = tonic::Status::with_details(tonic::Code::NotFound, "x", vec![0xff, 0x01].into());
        assert_eq!(error::detail(&raw), None);
    }
}
