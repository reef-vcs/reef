    /// A status with `code` and `message` whose details carry `detail`.
    pub fn status(code: tonic::Code, message: String, detail: &v1::ErrorDetail) -> tonic::Status {
        let envelope = tonic_types::Status {
            code: code as i32,
            message: message.clone(),
            details: vec![prost_types::Any {
                type_url: DETAIL_TYPE_URL.to_owned(),
                value: detail.encode_to_vec(),
            }],
        };
        tonic::Status::with_details(code, message, envelope.encode_to_vec().into())
    }

    /// The detail a status carries, if its details are a `google.rpc.Status`
    /// holding one.
    pub fn detail(status: &tonic::Status) -> Option<v1::ErrorDetail> {
        let details = status.details();
        if details.is_empty() {
            return None;
        }
        let envelope = tonic_types::Status::decode(details).ok()?;
        envelope
            .details
            .iter()
            .find(|any| any.type_url == DETAIL_TYPE_URL)
            .and_then(|any| v1::ErrorDetail::decode(any.value.as_slice()).ok())
    }
