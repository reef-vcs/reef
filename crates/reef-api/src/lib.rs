//! The Reef API: package `reef.api.v1`, compiled from `proto/` by
//! `build.rs` (`protox` and `tonic-prost-build`; generated code is not
//! committed). Its conventions and review checklist are ADR 0029.
//!
//! - [`v1`]: messages, a `<service>_server` module per service for the
//!   daemon, and a `<service>_client` module per service for clients.
//! - [`v0`]: the two files of 0.1.0's `reef.daemon.v0` that stay, frozen,
//!   so a daemon can answer a 0.1 client's `Daemon/Status` and a client can
//!   recognize a 0.1 daemon.
//! - [`error`]: the `google.rpc.Status` envelope of every v1 error's
//!   [`v1::ErrorDetail`].
//! - [`access`]: each method's `(reef.api.v1.access)` option.
//!
//! This crate depends on no other Reef crate, so a client needs nothing
//! else to speak the API.

